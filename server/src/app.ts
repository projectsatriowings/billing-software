import { registerDriveProxy } from './routes/driveProxy.ts';

/** Every module adds one `registerXxx(r)` line here. Nothing else in the server needs to change. */
export function buildRouter(tokens: { secret: string; ttlSeconds: number }): Router {
  const r = new Router();
  registerMeta(r);
  registerAuth(r, tokens);
  registerShop(r);
  registerUsers(r);
  registerItems(r);
  registerItemsBulk(r);
  registerCategories(r);
  registerParties(r);
  registerCreditNotes(r);
  registerInvoices(r);
  registerPurchases(r);
  registerReports(r);
  registerPayments(r);
  registerInventory(r);
  registerShifts(r);
  registerBranches(r);
  registerScannerBridge(r);
  registerExpenses(r);
  registerGst(r);
  registerHsn(r);
  registerCfdBridge(r);
  registerSalesAnalysis(r);
  registerDashboard(r);
  registerPaymentSettings(r);
  registerQrPayments(r);
  registerWebhooks(r);
  registerCardTerminals(r);
  registerStockTransfers(r);
  registerPromotions(r);
  registerUserManagement(r);
  registerBranchUsers(r);
  registerDriveProxy(r);
  return r;
}
